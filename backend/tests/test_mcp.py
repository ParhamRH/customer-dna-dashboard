def test_token_cannot_reach_other_tenants_or_brands(token, customers, world):
    s = build_server(default_token=token)
    # an asset belonging to customer A is invisible
    a_assets = customers["A"].admin.get("/v1/assets", params={"limit": 1}).json()["items"]
    if a_assets:
        r = _call(s, "get_asset_details", {"asset_id": a_assets[0]["id"]})
        assert r.is_error and "not found" in r.content[0].text
    # the token is pinned to one brand; another brand of the same customer is refused
    r = _call(s, "get_brand_identity", {"brand_id": customers["C"].brand_id})
    assert r.is_error and "restricted" in r.content[0].text
    # search never returns other tenants' assets
    res = _json(_call(s, "search_brand_assets", {"query": "organic geometry soft forms", "limit": 50}))
    a_ids = {x["id"] for x in customers["A"].admin.get("/v1/assets", params={"limit": 500}).json()["items"]}
    assert not ({x["asset_id"] for x in res["results"]} & a_ids)


def test_revoked_or_missing_token(world):
    r = _call(build_server(default_token="bdna_deadbeef_nope"), "list_brands")
    assert r.is_error
    tok = world["c"].admin.post("/v1/workspace/api-tokens", json={"name": "temp", "role": "viewer"}).json()
    world["c"].admin.post(f"/v1/workspace/api-tokens/{tok['id']}/revoke")
    r = _call(build_server(default_token=tok["token"]), "list_brands")
    assert r.is_error and "Invalid" in r.content[0].text



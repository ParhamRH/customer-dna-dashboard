"""Phase 7: MCP server — read-only tools, token scoping, tenant isolation."""
from __future__ import annotations

import asyncio
import json

import pytest
from mcp import Client

from app.mcp.server import build_server


def _call(server, tool: str, args: dict | None = None):
    async def run():
        async with Client(server) as c:
            return await c.call_tool(tool, args or {})
    return asyncio.run(run())


def _json(result) -> dict:
    if result.structured_content is not None:
        sc = result.structured_content
        return sc.get("result", sc) if isinstance(sc, dict) else sc
    return json.loads(result.content[0].text)


@pytest.fixture(scope="module")
def token(world):
    r = world["c"].admin.post("/v1/workspace/api-tokens", json={"name": "Claude MCP", "role": "viewer",
                                                               "scopes": [], "brand_id": world["brand_id"]})
    return r.json()["token"]


def test_tools_are_listed_and_read_only(token):
    async def run():
        async with Client(build_server(default_token=token)) as c:
            return [t.name for t in (await c.list_tools()).tools]
    names = set(asyncio.run(run()))
    expected = {"get_brand_identity", "get_visual_identity", "get_design_guidelines", "get_brand_language", "search_brand_assets",
                "search_aesthetic_concepts", "get_asset_details", "find_related_assets", "get_color_palette",
                "get_typography_system", "generate_brand_context"}
    assert expected <= names
    assert not any(n.startswith(("create", "update", "delete", "approve")) for n in names)


def test_identity_guidelines_and_search(token, world):
    s = build_server(default_token=token)
    ident = _json(_call(s, "get_brand_identity"))
    assert ident["brand"]["id"] == world["brand_id"]
    assert any(c["name"] == "Organic geometry" for c in ident["core_concepts"])
    g = _json(_call(s, "get_design_guidelines", {"project_type": "website_design"}))
    assert any(x["title"] == "Web layout guideline" for x in g["guidelines"])
    assert all(x["title"] != "Packaging guideline" for x in g["guidelines"])
    res = _json(_call(s, "search_brand_assets", {"query": "videos with slow cinematic camera movements"}))
    assert res["results"][0]["asset_id"] == world["ids"]["film.mp4"]
    concepts = _json(_call(s, "search_aesthetic_concepts", {"query": "organic"}))
    assert concepts["concepts"][0]["name"] == "Organic geometry"
    detail = _json(_call(s, "get_asset_details", {"asset_id": world["ids"]["organic.jpg"]}))
    assert detail["title"] == "Soft forms study" and all("note" in a for a in detail["analyses"])
    rel = _json(_call(s, "find_related_assets", {"asset_id": world["ids"]["organic.jpg"]}))
    assert rel["results"][0]["asset_id"] == world["ids"]["organic2.jpg"]
    ctx = _json(_call(s, "generate_brand_context", {"task_type": "image_generation", "mode": "compact"}))
    assert "Brand context" in ctx["context"] and ctx["sources"]


